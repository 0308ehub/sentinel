export type ConnectorFieldKind = "text" | "url" | "email" | "secret" | "textarea";

export interface ConnectorField {
  key: string;
  label: string;
  placeholder: string;
  kind: ConnectorFieldKind;
  required: boolean;
}

export interface ConnectorDefinition {
  id: string;
  name: string;
  category: string;
  description: string;
  logo?: string;
  fields: ConnectorField[];
  /** What Kismet files from this source onto the product graph. */
  filesAs: string;
  /** Existing setup page for connectors the server already reads. */
  setupHref?: string;
  live?: "slack" | "jira" | "databricks" | "google";
  /** How records move between the tool and the product graph. */
  flow?: string;
}

const secret = (key: string, label: string, placeholder: string): ConnectorField => ({
  key,
  label,
  placeholder,
  kind: "secret",
  required: true,
});

const text = (key: string, label: string, placeholder: string, required = true): ConnectorField => ({
  key,
  label,
  placeholder,
  kind: "text",
  required,
});

const url = (key: string, label: string, placeholder: string): ConnectorField => ({
  key,
  label,
  placeholder,
  kind: "url",
  required: true,
});

const email = (key: string, label: string, placeholder: string): ConnectorField => ({
  key,
  label,
  placeholder,
  kind: "email",
  required: true,
});

